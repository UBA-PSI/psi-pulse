interface IEmailData {
    head: { to: string, subject: string },
    body: any
}

export const sendEmail = async (data: IEmailData) => {
    const transporter = nodemailer.createTransport({
        host: useRuntimeConfig().mailSecrets.EMAIL_HOST,
        port: 587,
        secure: false,
        requireTLS: true,
        auth: {
            user: useRuntimeConfig().mailSecrets.EMAIL_USER,
            pass: useRuntimeConfig().mailSecrets.EMAIL_PASS
        },
    })

    const mailOptions = {
        from: 'Pulse <pulse.psi@uni-bamberg.de>',
        to: data.head.to,
        subject: data.head.subject,
        html: "<p>" + data.body + "</p>"
    }
    await transporter.sendMail(mailOptions)
    transporter.verify(function (error, success) {
        if (error) {
            console.log(error);
        } else if (success) {
            console.log("Server is ready to take our messages");
        } else {
            console.log("Server is not ready to take our messages");
        }
    });
}
