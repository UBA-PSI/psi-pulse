const generateQuestionsBody = (data: EmailEntry): string => {
    let body = ""

    for (const question of data.questions) {
        body = body.concat(`<br><br>`)
        if (question.group === "no-group") {
            body = body.concat(`<span>${question.page}</span>`)
        } else {
            body = body.concat(`<span>${question.page} – ${question.group}</span>`)
        }
        body = body.concat(`<br>`)
        body = body.concat(`<span><b>${question.text}</b></span>`)
        body = body.concat(`<br><a href="${hostUrl}/answer/question/${question.id}?token=${question.token}">Answer this</a>`)
    }

    return body
}

